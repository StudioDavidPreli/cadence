export const EXPORT_FORMAT_KEYS = EXPORT_FORMATS.map(f => f.key)

export function exportFormat(key) {
  const format = EXPORT_FORMATS.find(f => f.key === key)
  if (!format) throw new Error(`Unknown export format: ${key}`)
  return format
}

// The file for one format and one state: what the download writes and what
// the counter records. Export and Copy both call this rather than holding the
// text in state, so the text is always the state at the moment of the click.
export function exportFile(key, state, { deviations = [], presetLabel = null } = {}) {
  const format = exportFormat(key)
  return {
    filename: format.filename,
    mime: format.mime,
    wire: format.wire,
    text: format.stringify(state, { deviations, presetLabel }),
  }
}
