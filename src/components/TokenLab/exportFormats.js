// The export format table: everything Token Lab knows about the seven files it
// can write, in one place (six at the modal's launch; Figma joined 2026-09-15).
//
// Before the export modal (2026-09-15) this knowledge was spread across the
// tool bar section: a four-button toggle, an `exportText()` chain of ifs, a
// filename map, a wire-name map for the counter, and a second copy of the
// stringifier list in the capture rig with the highlight language added. Six
// formats made that arrangement worse in every place at once, so the table is
// the single source and every surface (the modal, the tool bar, the rig, the
// tests) reads it.
//
// Fields, per format:
//   key          the UI's internal id, stable across renames of anything else
//   label        the name a reader sees in the format list
//   description  one sentence saying what the file is for and who reads it
//   filename     what the download is called; each carries its conventional
//                extension so the file opens as its own type
//   mime         the Blob type, matched to the extension
//   language     the Prism grammar the preview highlights with
//   wire         the name the /api/event counter records. The counter speaks
//                the endpoint's contract ('json', 'framer-motion') rather than
//                the UI's keys ('flat', 'fm') so the metrics report reads
//                without a decoder ring. `exportFormats.test.js` pins this
//                column to the Worker's allowlist by reading the Worker source.
//   reimports    whether importTokens can read the file back. DTCG and flat
//                are interchange formats; the other four are destinations.
//   carriesDeviations
//                whether the off-system appendix rides this file (see below).
//                The modal reads it to say so beside the file rather than
//                letting a reader assume a deviation travelled when it did not.
//   stringify    (state, opts) -> text. All six serialize from the package's
//                single stateToExport object, so the files cannot drift apart.
//
// Off-system deviations (a demo running a literal in place of a token) ride the
// four token-document formats as an appendix in each one's idiom. After Effects
// and Flow do not carry them: the AE script writes a control layer and the Flow
// library is a curve set, and neither has a place for "this one demo declined
// the token". The table says so per format rather than the modal guessing.
import {
  toDtcgJson,
  toFlatJson,
  toCssVars,
  toFramerMotion,
  toAfterEffects,
  toFlow,
  toFigmaJson,
} from 'cadence-tokens'
// The package version, for the After Effects script header ("Generated by
// cadence-tokens 2.0.0"). Read from the manifest rather than restated here so
// a version bump in the package cannot leave the shipped script claiming an
// older one. A relative import because the package's exports map exposes only
// its entry and two dist files, and this is the one consumer of the manifest.
import tokensPackage from '../../../packages/tokens/package.json'

export const TOKENS_PACKAGE_VERSION = tokensPackage.version

// The label a state export is headed with. The active preset's name when the
// set matches one, and "Custom" when it does not: a set the user has edited is
// no longer that preset, and a script headed "Standard preset" that retimes a
// comp to something else would misdescribe itself. Same rule as the audit's
// heading, which uses null for the same case; the AE header needs a word.
export function exportLabel(presetLabel) {
  return presetLabel ?? 'Custom'
}

